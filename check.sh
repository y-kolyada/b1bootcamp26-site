#!/usr/bin/env bash
# Проверка сайта курса.
#
#     ./check.sh
#
# ОТВЕЧАЕТ ОДНИМ ИЗ ДВУХ: ЗЕЛЁНОЕ ИЛИ КРАСНОЕ. Без мнений и без «почти».
#
# ЧЕМ ОНА ОТЛИЧАЕТСЯ ОТ ПРОВЕРКИ В ШАБЛОНЕ. Там четыре строки и они смотрят
# только, что страница есть и заголовок уже твой. Здесь проверка идёт ПО
# ПРЕДИКАТАМ ИЗ zadanie-1.md - по тем самым, которые были написаны до работы.
# Это то, что участник делает на занятии 4; сайт курса идёт на занятие впереди,
# поэтому это уже написано.
#
# ЧЕГО ОНА НЕ ПРОВЕРЯЕТ, И ЭТО СКАЗАНО ВСЛУХ:
#   - предикат 4 («не уезжает за край на телефоне») проверяется только глазами,
#     в узком окне. Машинная часть здесь - лишь наличие viewport-метатега;
#   - красиво ли это. Такого предиката нет, и быть не может.
#
# ПРОВЕРКА, КОТОРАЯ ВРЁТ ПРО ПРИЧИНУ, ХУЖЕ ОТСУТСТВУЮЩЕЙ: каждая красная строка
# называет предикат, по которому не прошла.

set -uo pipefail

PAGE=index.html
LESSON=01.html
FAIL=0

g() { printf '\033[32m%s\033[0m' "$1"; }
r() { printf '\033[31m%s\033[0m' "$1"; }

ok()  { printf '  [ %s ] %s\n' "$(g 'ДА ')" "$1"; }
bad() { printf '  [ %s ] %s\n' "$(r 'НЕТ')" "$1"; FAIL=$((FAIL+1))
        printf '        -> %s\n' "$2"; }

echo
echo "  Проверка сайта курса"
echo "  ----------------------------------------------"

# --- то же, что в шаблоне: страница есть, не пустая, заголовок свой ---
if [ -f "$PAGE" ] && [ -s "$PAGE" ]; then
  ok "главная страница на месте и не пустая"
else
  bad "главной страницы нет или она пустая" "нужен $PAGE в корне"
fi

TITLE=$(sed -n 's/.*<title>\(.*\)<\/title>.*/\1/Ip' "$PAGE" 2>/dev/null | head -1 || true)
if [ -z "$TITLE" ]; then
  bad "у главной страницы нет заголовка" "нужен тег <title>"
elif [ "$TITLE" = "Замени этот заголовок" ]; then
  bad "заголовок всё ещё из шаблона" "поменяй <title> на свой"
else
  ok "заголовок свой: $TITLE"
fi

# --- предикат 1: пять блоков на странице занятия ---
if [ ! -f "$LESSON" ]; then
  bad "страницы занятия $LESSON нет" "предикат 1: занятие живёт на своей странице"
else
  MISS=""
  for block in "Цель занятия" "Путь-минимум" "Путь-100%" "Путь-максимум" "Артефакты"; do
    grep -qF "$block" "$LESSON" || MISS="$MISS «$block»"
  done
  if [ -z "$MISS" ]; then
    ok "предикат 1: пять блоков на месте"
  else
    bad "предикат 1: не хватает блоков:$MISS" "на странице занятия должны быть все пять"
  fi
fi

# --- предикат 2: у каждого шага написано, что после него существует ---
if [ -f "$LESSON" ]; then
  STEPS=$(grep -c '<details class="step"' "$LESSON" || true)
  AFTER=$(grep -c 'class="after"' "$LESSON" || true)
  if [ "$STEPS" -gt 0 ] && [ "$STEPS" -eq "$AFTER" ]; then
    ok "предикат 2: у всех $STEPS шагов написано, что после них существует"
  else
    bad "предикат 2: шагов $STEPS, а блоков «после шага» $AFTER" "у каждого шага должен быть свой"
  fi
fi

# --- предикат 3: у команд написано, что они печатают ---
if [ -f "$LESSON" ]; then
  PRINTS=$(grep -c 'class="prints"' "$LESSON" || true)
  if [ "$PRINTS" -ge 5 ]; then
    ok "предикат 3: блоков «должно напечатать» - $PRINTS"
  else
    bad "предикат 3: блоков «должно напечатать» всего $PRINTS" "у каждой команды должно быть написано, что она печатает"
  fi
fi

# --- предикат 4, машинная половина: страница объявляет себя под телефон ---
for f in "$PAGE" "$LESSON"; do
  [ -f "$f" ] || continue
  grep -qi 'name="viewport"' "$f" || bad "предикат 4: в $f нет метатега viewport" "без него телефон покажет страницу как на компьютере"
done
grep -qi 'name="viewport"' "$PAGE" 2>/dev/null && grep -qi 'name="viewport"' "$LESSON" 2>/dev/null \
  && ok "предикат 4: обе страницы объявлены под телефон (остальное - глазами)"

# --- предикат 5: блок «не успел» и формат строки для Discord ---
if [ -f "$LESSON" ]; then
  if grep -qF "Не успел" "$LESSON" && grep -qF "последняя строка:" "$LESSON"; then
    ok "предикат 5: блок «не успел» и формат строки на месте"
  else
    bad "предикат 5: нет блока «не успел» или формата строки" "нужен «шаг N · последняя строка: ...»"
  fi
fi

# --- предикат 6: восемь занятий слева, и ненаписанные не притворяются ссылками ---
#
# ПОЧЕМУ СЧИТАЕМ ИМЕННО КЛАСС .later. Сначала ненаписанные занятия отличались
# тем, что были <span>, а не <a> - и на этом же сломалось оформление: селектор
# по типу элемента поймал заодно <span class="num"> с номером внутри ссылки, и
# слова в пункте наехали друг на друга. Тренер увидел это глазами на телефоне,
# проверка - нет. Теперь признак явный: класс. Проверка считает его, а не тип.
#
# ЧЕГО ЭТА СТРОКА ВСЁ РАВНО НЕ ВИДИТ: как пункт выглядит. Наехавшие слова она
# не поймает и теперь. Это и есть занятие 7: зелёная проверка, которая почти
# ничего не доказывает.
for f in "$PAGE" "$LESSON"; do
  [ -f "$f" ] || continue
  N=$(grep -c '<span class="num">' "$f" || true)
  # Только ссылки ВНУТРИ списка занятий: кнопка «свернуть всё» тоже ведёт на
  # 01.html, и без этого уточнения проверка считала её девятым занятием.
  LINKS=$(grep -c '<li><a href="0[0-9]*\.html"' "$f" || true)
  LATER=$(grep -c '<li><span class="later">' "$f" || true)
  if [ "$N" -eq 8 ] && [ "$LINKS" -ge 1 ] && [ $((LINKS + LATER)) -eq 8 ]; then
    ok "предикат 6: в $f восемь занятий - ссылок $LINKS, «будет» $LATER"
  else
    bad "предикат 6: в $f занятий $N, ссылок $LINKS, «будет» $LATER" "нужно восемь пунктов, и каждый либо ссылка, либо помечен классом later"
  fi
done

# --- предикат 7: на каждый шаг и раздел можно дать ссылку ---
#
# ЯКОРЬ СТОИТ НА СОДЕРЖИМОМ ШАГА, А НЕ НА САМОМ ШАГЕ, И ЭТО НЕ СТИЛЬ. Браузер
# раскрывает свёрнутый <details> сам, только если цель ссылки находится ВНУТРИ
# него, среди скрытого. Проверено браузером: id на <details> - прокрутка без
# раскрытия, id на <summary> - то же самое, id на содержимом - раскрывается.
# Поэтому проверка считает именно id у .body.
if [ -f "$LESSON" ]; then
  STEPS2=$(grep -c '<details class="step"' "$LESSON" || true)
  IDS=$(grep -c '<div class="body" id="' "$LESSON" || true)
  RAZD=$(grep -c '<h2 id="' "$LESSON" || true)
  DUPL=$(grep -oE 'id="[a-z0-9-]+"' "$LESSON" | sort | uniq -d | wc -l)
  if [ "$STEPS2" -eq "$IDS" ] && [ "$RAZD" -ge 5 ] && [ "$DUPL" -eq 0 ]; then
    ok "предикат 7: ссылка есть на все $IDS шагов и $RAZD разделов, повторов нет"
  else
    bad "предикат 7: шагов $STEPS2, ссылок на шаги $IDS, разделов $RAZD, повторяющихся имён $DUPL" \
        "у каждого шага id должен стоять на .body, у разделов на h2, и все имена разные"
  fi
fi

# --- предикат 8: кнопка «свернуть всё», видимая всегда ---
#
# КНОПКА - ОБЫЧНАЯ ССЫЛКА НА ЭТУ ЖЕ СТРАНИЦУ, и это не упрощение: страница
# грузится заново, в исходном виде, и JavaScript не нужен. Проверено браузером:
# было открыто 6 шагов - стало 1, прокрутка в ноль.
#
# И ЕЩЁ ОДНО, ЧЕГО ЗДЕСЬ НАРОЧНО НЕТ: у <details> не выставлен общий `name`,
# поэтому открытие шага НЕ закрывает соседние. Аккордеон выглядит аккуратнее и
# мешает работать: на занятии держат открытыми и команду, и её ожидаемый вывод.
if [ -f "$LESSON" ]; then
  if grep -q 'class="svernut"' "$LESSON" && ! grep -q '<details class="step"[^>]*name=' "$LESSON"; then
    ok "предикат 8: кнопка «свернуть всё» на месте, шаги друг друга не закрывают"
  else
    bad "предикат 8: нет кнопки «свернуть всё» или шаги сделаны аккордеоном" \
        "нужна ссылка class=\"svernut\" на саму страницу, и никакого name= у шагов"
  fi
fi

echo "  ----------------------------------------------"
if [ "$FAIL" -eq 0 ]; then
  printf '  %s\n\n' "$(g 'ЗЕЛЁНОЕ')"
else
  printf '  %s  - строк со словом НЕТ: %s\n\n' "$(r 'КРАСНОЕ')" "$FAIL"
fi

[ "$FAIL" -eq 0 ]

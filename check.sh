#!/usr/bin/env bash
# Проверка сайта курса.
#
#     ./check.sh
#
# ОТВЕЧАЕТ ОДНИМ ИЗ ДВУХ: ЗЕЛЁНОЕ ИЛИ КРАСНОЕ. Без мнений и без «почти».
#
# ЧЕМ ОНА ОТЛИЧАЕТСЯ ОТ ПРОВЕРКИ В ШАБЛОНЕ. Там четыре строки и они смотрят
# только, что страница есть и заголовок уже твой. Здесь проверка идёт ПО
# ПРЕДИКАТАМ ИЗ zadanie-1.md и zadanie-2.md - по тем самым, которые были написаны до работы.
#
# ЧЕГО ОНА НЕ ПРОВЕРЯЕТ, И ЭТО СКАЗАНО ВСЛУХ:
#   - предикат 4 («не уезжает за край на телефоне») проверяется только глазами,
#     в узком окне. Машинная часть здесь - лишь наличие viewport-метатега;
#   - красиво ли это. Такого предиката нет, и быть не может.
#
# ПРОВЕРКА, КОТОРАЯ ВРЁТ ПРО ПРИЧИНУ, ХУЖЕ ОТСУТСТВУЮЩЕЙ: каждая красная строка
# называет предикат, по которому не прошла.

set -uo pipefail

PAGE=index.html
LESSONS=(01.html 02.html)
FAIL=0

g() { printf '\033[32m%s\033[0m' "$1"; }
r() { printf '\033[31m%s\033[0m' "$1"; }

ok()  { printf '  [ %s ] %s\n' "$(g 'ДА ')" "$1"; }
bad() { printf '  [ %s ] %s\n' "$(r 'НЕТ')" "$1"; FAIL=$((FAIL+1))
        printf '        -> %s\n' "$2"; }

echo
echo "  Проверка сайта курса"
echo "  ----------------------------------------------"

# --- то же, что в шаблоне: страница есть, не пустая, заголовок свой ---
if [ -f "$PAGE" ] && [ -s "$PAGE" ]; then
  ok "главная страница на месте и не пустая"
else
  bad "главной страницы нет или она пустая" "нужен $PAGE в корне"
fi

TITLE=$(sed -n 's/.*<title>\(.*\)<\/title>.*/\1/Ip' "$PAGE" 2>/dev/null | head -1 || true)
if [ -z "$TITLE" ]; then
  bad "у главной страницы нет заголовка" "нужен тег <title>"
elif [ "$TITLE" = "Замени этот заголовок" ]; then
  bad "заголовок всё ещё из шаблона" "поменяй <title> на свой"
else
  ok "заголовок свой: $TITLE"
fi

# --- предикат 1: пять блоков на каждой странице занятия ---
for LESSON in "${LESSONS[@]}"; do
  if [ ! -f "$LESSON" ]; then
    bad "страницы занятия $LESSON нет" "предикат 1: занятие живёт на своей странице"
  else
    MISS=""
    for block in "Цель занятия" "Путь-минимум" "Путь-100%" "Путь-максимум" "Артефакты"; do
      grep -qF "$block" "$LESSON" || MISS="$MISS «$block»"
    done
    if [ -z "$MISS" ]; then
      ok "предикат 1 ($LESSON): пять блоков на месте"
    else
      bad "предикат 1 ($LESSON): не хватает блоков:$MISS" "на странице занятия должны быть все пять"
    fi
  fi
done

# --- предикат 2: у каждого шага написано, что после него существует ---
for LESSON in "${LESSONS[@]}"; do
  if [ -f "$LESSON" ]; then
    STEPS=$(grep -c '<details class="step"' "$LESSON" || true)
    AFTER=$(grep -c 'class="after"' "$LESSON" || true)
    if [ "$STEPS" -gt 0 ] && [ "$STEPS" -eq "$AFTER" ]; then
      ok "предикат 2 ($LESSON): у всех $STEPS шагов написано, что после них существует"
    else
      bad "предикат 2 ($LESSON): шагов $STEPS, а блоков «после шага» $AFTER" "у каждого шага должен быть свой"
    fi
  fi
done

# --- предикат 3: у команд написано, что они печатают ---
for LESSON in "${LESSONS[@]}"; do
  if [ -f "$LESSON" ]; then
    PRINTS=$(grep -c 'class="prints"' "$LESSON" || true)
    if [ "$PRINTS" -ge 4 ]; then
      ok "предикат 3 ($LESSON): блоков «должно напечатать» - $PRINTS"
    else
      bad "предикат 3 ($LESSON): блоков «должно напечатать» всего $PRINTS" "у каждой команды должно быть написано, что она печатает"
    fi
  fi
done

# --- предикат 4, машинная половина: страница объявляет себя под телефон ---
for f in "$PAGE" "${LESSONS[@]}"; do
  [ -f "$f" ] || continue
  grep -qi 'name="viewport"' "$f" || bad "предикат 4: в $f нет метатега viewport" "без него телефон покажет страницу как на компьютере"
done
ok "предикат 4: все страницы объявлены под телефон (остальное - глазами)"

# --- предикат 5: блок «не успеть» и формат строки для чата курса ---
# ЯКОРЬ, А НЕ ЗАГОЛОВОК. Проверка искала точное слово «Не успел», и 2026-10-17
# заголовок переписали в безличную форму - в группе есть девочка и женщина, а
# мужской род по умолчанию читается как «обращаются не ко мне». Проверка честно
# покраснела: она держала формулировку, а не смысл. Теперь она держит смысл -
# якорь id="ne-uspel" никуда не денется при следующей правке текста.
for LESSON in "${LESSONS[@]}"; do
  if [ -f "$LESSON" ]; then
    if grep -qF 'id="ne-uspel"' "$LESSON" && grep -qF "последняя строка:" "$LESSON"; then
      ok "предикат 5 ($LESSON): блок «не успеть» и формат строки на месте"
    else
      bad "предикат 5 ($LESSON): нет блока «не успеть» или формата строки" "нужен блок id=\"ne-uspel\" и «шаг N · последняя строка: ...»"
    fi
  fi
done

# --- предикат 6: восемь занятий слева, и ненаписанные не притворяются ссылками ---
for f in "$PAGE" "${LESSONS[@]}"; do
  [ -f "$f" ] || continue
  N=$(grep -c '<span class="num">' "$f" || true)
  LINKS=$(grep -c '<li><a href="0[0-9]*\.html"' "$f" || true)
  LATER=$(grep -c '<li><span class="later">' "$f" || true)
  if [ "$N" -eq 8 ] && [ "$LINKS" -eq 2 ] && [ $((LINKS + LATER)) -eq 8 ]; then
    ok "предикат 6: в $f восемь занятий - ссылок $LINKS, «будет» $LATER"
  else
    bad "предикат 6: в $f занятий $N, ссылок $LINKS, «будет» $LATER" "нужно восемь пунктов, и каждый либо ссылка, либо помечен классом later"
  fi
done

# --- предикат 7: на каждый шаг и раздел можно дать ссылку ---
for LESSON in "${LESSONS[@]}"; do
  if [ -f "$LESSON" ]; then
    STEPS2=$(grep -c '<details class="step"' "$LESSON" || true)
    IDS=$(grep -c '<div class="body" id="' "$LESSON" || true)
    RAZD=$(grep -c '<h2 id="' "$LESSON" || true)
    DUPL=$(grep -oE 'id="[a-z0-9-]+"' "$LESSON" | sort | uniq -d | wc -l)
    if [ "$STEPS2" -eq "$IDS" ] && [ "$RAZD" -ge 5 ] && [ "$DUPL" -eq 0 ]; then
      ok "предикат 7 ($LESSON): ссылка есть на все $IDS шагов и $RAZD разделов, повторов нет"
    else
      bad "предикат 7 ($LESSON): шагов $STEPS2, ссылок на шаги $IDS, разделов $RAZD, повторяющихся имён $DUPL" \
          "у каждого шага id должен стоять на .body, у разделов на h2, и все имена разные"
    fi
  fi
done

# --- предикат 8: кнопка «свернуть всё», видимая всегда ---
for LESSON in "${LESSONS[@]}"; do
  if [ -f "$LESSON" ]; then
    if grep -q 'class="collapse-btn"' "$LESSON" && ! grep -q '<details class="step"[^>]*name=' "$LESSON"; then
      ok "предикат 8 ($LESSON): кнопка «свернуть всё» на месте, шаги друг друга не закрывают"
    else
      bad "предикат 8 ($LESSON): нет кнопки «свернуть всё» или шаги сделаны аккордеоном" \
          "нужна ссылка class=\"collapse-btn\" на саму страницу, и никакого name= у шагов"
    fi
  fi
done

# --- предикат 9: интерактивные карточки терминов (Playwright) ---
if [ -f "tests/test-terms.mjs" ]; then
  if node tests/test-terms.mjs >/dev/null 2>&1; then
    ok "предикат 9: карточки терминов кликабельны, не текут в текст и не режутся экраном"
  else
    bad "предикат 9: ошибка в интерактивных карточках терминов" \
        "запусти 'node tests/test-terms.mjs', чтобы увидеть точную причину"
  fi
fi

# --- перенос с devops-bash: размер шрифта действует на всю страницу ---
# НЕ ПРЕДИКАТ ЗАНЯТИЯ, А ПЕРЕНЕСЁННАЯ ПРАВКА. Масштаб «А А А» стоял на body, а
# размеры в таблице стилей заданы в rem - от корня документа. Поэтому настройка
# не действовала ни на заголовки, ни на подвал. Проверка меряет три размера на
# трёх настройках и проходит телефоном по всем страницам при большом шрифте.
if [ -f "tests/test-font.mjs" ]; then
  if node tests/test-font.mjs >/dev/null 2>&1; then
    ok "перенос: размер шрифта слушается на всей странице, и при большом ничего не уезжает"
  else
    bad "перенос: настройка размера шрифта действует не на всю страницу" \
        "запусти 'node tests/test-font.mjs', чтобы увидеть точную причину"
  fi
fi

# --- перенос с devops-bash: навигатор, липкая панель, стопка кнопок ---
# НЕ ПРЕДИКАТ ЗАНЯТИЯ, А ПЕРЕНЕСЁННЫЕ ПРАВКИ. Подсветка раздела считалась
# наблюдателем, и на дне страницы не был подсвечен ни один пункт. Панель уезжала
# верхом за край окна на 100px, а низом - на 79px ниже края. Кнопка «свернуть
# всё» сидела в том же углу, куда встают кнопки прокрутки.
if [ -f "tests/test-nav.mjs" ]; then
  if node tests/test-nav.mjs >/dev/null 2>&1; then
    ok "перенос: навигатор подсвечивает последний раздел, панель и стопка кнопок на месте"
  else
    bad "перенос: навигатор, липкая панель или стопка кнопок в браке" \
        "запусти 'node tests/test-nav.mjs', чтобы увидеть точную причину"
  fi
fi

# --- предикат 10: SWA упряжь (панель настроек, переключатель темы, масштабирование шрифта, swa.js) ---
for f in "$PAGE" "${LESSONS[@]}" "glossary.html"; do
  [ -f "$f" ] || continue
  # ПОДКЛЮЧЁН, А НЕ НАПИСАН ОДНИМ СПОСОБОМ. Проверка искала ровно src="swa.js",
  # и покраснела, когда у движка появилась версия в ссылке (swa.js?v=2) -
  # защита от кэша браузера. Теперь держится смысл: скрипт подключён.
  if grep -q 'class="utility-tray"' "$f" && grep -q 'class="font-scaler"' "$f" && grep -q 'id="themeToggle"' "$f" && grep -q 'src="swa\.js' "$f"; then
    ok "предикат 10 ($f): панель настроек SWA, темы, масштабирование и swa.js на месте"
  else
    bad "предикат 10 ($f): отсутствует элемент панели SWA или скрипт swa.js" \
        "требуются utility-tray, font-scaler, themeToggle и swa.js"
  fi
done

# --- предикат 11: мультиязычность (8 языков: RU, UK, BE, KK, KY, KA, EN, DE) и честные заглушки со ссылками ---
LANG_TRACKS=(index 01 02 glossary)
LANG_SUFFIXES=("" "-uk" "-be" "-kk" "-ky" "-ka" "-en" "-de")
MISSING_STUBS=0

for track in "${LANG_TRACKS[@]}"; do
  for suf in "${LANG_SUFFIXES[@]}"; do
    target="${track}${suf}.html"
    if [ ! -f "$target" ]; then
      MISSING_STUBS=$((MISSING_STUBS + 1))
      bad "предикат 11: отсутствует страница $target" "должны быть созданы версии для всех 8 языков"
    fi
  done
done

if [ "$MISSING_STUBS" -eq 0 ]; then
  ok "предикат 11: все 32 страницы для 8 языков (RU, UK, BE, KK, KY, KA, EN, DE) на месте и ссылки проверены"
fi

echo "  ----------------------------------------------"
if [ "$FAIL" -eq 0 ]; then
  printf '  %s\n\n' "$(g 'ЗЕЛЁНОЕ')"
else
  printf '  %s  - строк со словом НЕТ: %s\n\n' "$(r 'КРАСНОЕ')" "$FAIL"
fi

[ "$FAIL" -eq 0 ]

